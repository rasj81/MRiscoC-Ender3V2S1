#!/usr/bin/env python3
"""Build the "(Sprite Pro, Turbo)" Orca profile set from the "(Sprite Pro, Fast)" set.

Run from printer-config/:  python3 tools/turbo.py
Reads  E3V2-SpritePro-Wifi/orca-profiles/{machine,process}/*Fast*.json and orca-profiles/filament/*.json
Writes Turbo copies next to them. The Fast files are never modified.
"""
import json, os, glob, re

BUILD = 'E3V2-SpritePro-Wifi/orca-profiles'
FIL = 'orca-profiles/filament'
INFO = 'sync_info = \nuser_id = \nsetting_id = \nbase_id = \nupdated_time = 0\n'
TAG = 'Turbo profile: generated by printer-config/tools/turbo.py from the Fast set.'

# Nominal speeds (mm/s) per nozzle. Orca also caps every move by the filament's
# max volumetric speed, so the bigger nozzles end up flow-limited well below these.
SPEEDS = {
    #       outer inner sparse solid top gap
    '0.2': (150, 180, 200, 150, 60, 50),
    '0.4': (150, 200, 200, 150, 60, 50),
    '0.6': (120, 160, 160, 120, 50, 40),
    '0.8': (90, 120, 120, 90, 40, 30),
    '1.0': (70, 100, 100, 70, 35, 25),
}
ACCEL = dict(default_acceleration='4000', outer_wall_acceleration='2500',
             inner_wall_acceleration='4000', top_surface_acceleration='2000',
             sparse_infill_acceleration='100%', internal_solid_infill_acceleration='100%',
             travel_acceleration='5000', initial_layer_acceleration='500',
             bridge_acceleration='50%')
MACHINE_LIMITS = dict(  # [normal, stealth]
    machine_max_acceleration_x=['5000', '500'], machine_max_acceleration_y=['5000', '500'],
    machine_max_acceleration_extruding=['5000', '500'],
    machine_max_acceleration_travel=['5000', '500'],
    machine_max_speed_x=['500', '500'], machine_max_speed_y=['500', '500'])
# Turbo filaments: higher flow ceiling and a hotter nozzle to melt it.
FILAMENT = {
    'Inland PLA+': dict(vol='18', temp='220', first='220'),
    'DEEPLEE PLA Pro (Amazon)': dict(vol='17', temp='220', first='220'),
    'Inland PETG+': dict(vol='14', temp='245', first='245'),
}

def turbo(s): return s.replace('(Sprite Pro, Fast)', '(Sprite Pro, Turbo)')

def write(path, d):
    with open(path, 'w') as f:
        json.dump(dict(sorted(d.items())), f, indent=4)
    with open(path[:-5] + '.info', 'w') as f:
        f.write(INFO)

def tree(o):  # rename every Fast reference inside a preset
    if isinstance(o, str): return turbo(o)
    if isinstance(o, list): return [tree(x) for x in o]
    if isinstance(o, dict): return {k: tree(v) for k, v in o.items()}
    return o

printers = []
for src in sorted(glob.glob(f'{BUILD}/machine/*(Sprite Pro, Fast)*.json')):
    m = tree(json.load(open(src)))
    m.update(MACHINE_LIMITS, inherits='', emit_machine_limits_to_gcode='1',
             printer_model='Creality Ender-3 V2',  # not the doubled "Creality Creality"
             printer_notes=TAG)
    m['print_host'] = m['printhost_apikey'] = ''  # never commit OctoPrint secrets
    assert 'M84 X Y E' in m['machine_end_gcode'] and 'M300' in m['machine_end_gcode']
    printers.append(m['name'])
    write(turbo(src), m)
    print('printer ', m['name'])

for src in sorted(glob.glob(f'{BUILD}/process/*(Sprite Pro, Fast)*.json')):
    p = tree(json.load(open(src)))
    d = re.search(r'(\d\.\d) nozzle', p['name']).group(1)
    o, i, sp, so, t, g = SPEEDS[d]
    p.update(ACCEL, inherits='', notes=TAG,
             outer_wall_speed=str(o), inner_wall_speed=str(i), sparse_infill_speed=str(sp),
             internal_solid_infill_speed=str(so), top_surface_speed=str(t),
             gap_infill_speed=str(g), travel_speed='250', bridge_speed='30')
    write(turbo(src), p)
    print('process ', p['name'], '| walls', o, i, '| infill', sp, '| accel 4000/outer 2500')

for name, v in FILAMENT.items():
    f = json.load(open(f'{FIL}/{name}.json'))
    n = f'{name} (Turbo)'
    f.update(name=n, filament_settings_id=[n], inherits='', compatible_printers=printers,
             compatible_printers_condition='', filament_max_volumetric_speed=[v['vol']],
             nozzle_temperature=[v['temp']], nozzle_temperature_initial_layer=[v['first']],
             filament_notes=[TAG])
    write(f'{FIL}/{n}.json', f)
    print('filament', n, v)
